function translate(value){
 const trimmed=value.trim();
 if(!trimmed)return null;
 if(EN[trimmed])return EN[trimmed];
 let match=trimmed.match(/^(Postingan saya|Disimpan|Opportunity saya|Materi saya) \((\d+)\)$/);
 if(match)return `${EN[match[1]]} (${match[2]})`;
 match=trimmed.match(/^(\d+) informasi$/);
 if(match)return `${match[1]} opportunities`;
 return null;
}
export function translateInterface(root,language){
 if(language!=='en'||!root||typeof document.createTreeWalker!=='function')return;
 const walk=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);
 const nodes=[];while(walk.nextNode())nodes.push(walk.currentNode);
 for(const node of nodes){
   const el=node.parentElement;
   if(!el || el.closest('script,style,.post-main,.post-author,.comment-item,.xp-message,.gm-user-content,.profile-bio,.profile-description'))continue;
   const updated=translate(node.nodeValue);
   if(updated){const leading=node.nodeValue.match(/^\s*/)?.[0]||'',trailing=node.nodeValue.match(/\s*$/)?.[0]||'';node.nodeValue=leading+updated+trailing;}
 }
 root.querySelectorAll('[placeholder]').forEach(input=>{if(placeholders[input.placeholder])input.placeholder=placeholders[input.placeholder];});
 root.querySelectorAll('[aria-label]').forEach(el=>{if(EN[el.getAttribute('aria-label')])el.setAttribute('aria-label',EN[el.getAttribute('aria-label')]);});
}
