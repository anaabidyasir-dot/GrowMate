import assert from 'node:assert/strict';
import {initialAccount} from '../src/data.js';
import {REPORT_REASONS,ensureCommunity,isBlocked,setBlocked,isHidden,setHidden,saveReport,logActivity,shareLink,getIncomingShare} from '../src/community.js';
import {opportunityById, communityOpportunitiesFor} from '../src/experiences.js';

const db=initialAccount({email:'contoh@example.test',name:'Penguji'});
assert.equal(ensureCommunity(db).blocked.length,0);
db.following.push('kenzie');db.invites=['kenzie'];
assert.equal(setBlocked(db,'kenzie',true),true);
assert.equal(isBlocked(db,'kenzie'),true);
assert.equal(db.following.includes('kenzie'),false,'blocked account is unfollowed');
assert.equal(db.invites.includes('kenzie'),false,'pending invite removed when blocked');
assert.equal(setBlocked(db,'me',true),false,'cannot block own account');
assert.equal(opportunityById(db,'community-ux'),undefined,'obsolete no-poster card must be removed');
assert.equal(communityOpportunitiesFor('damian',db).length,0,'no fake community opportunity for a peer');
assert.equal(setHidden(db,'post','p1',true,'Merancang antarmuka'),true);
assert.equal(isHidden(db,'post','p1'),true);
assert.equal(setHidden(db,'post','p1',false),true);
assert.equal(isHidden(db,'post','p1'),false);
assert.equal(setHidden(db,'opportunity','fes-global',true,'Futurepreneur Global Bootcamp 2027'),true);
assert.equal(opportunityById(db,'fes-global'),undefined,'hidden opportunity removed from catalog');
assert.equal(setHidden(db,'opportunity','fes-global',false),true);
assert.equal(!!opportunityById(db,'fes-global'),true);
assert.equal(saveReport(db,'post','p1','Alasan yang tidak ada'),false);
assert.equal(saveReport(db,'user','kenzie',REPORT_REASONS[1],'<script>alert(1)</script>'),true);
assert.equal(db.community.reports.length,1);
assert.equal(db.community.reports[0].status,'local');
logActivity(db,'liked','post','p1');
assert.equal(db.community.activity[0].action,'liked');
assert.ok(JSON.parse(JSON.stringify(db)).community.reports.length,'state survives JSON storage');
setBlocked(db,'kenzie',false);
assert.equal(isBlocked(db,'kenzie'),false);
globalThis.location={href:'https://growmate.example/#home',search:'?gm-share=post&id=p1'};
const url=shareLink('post','p1');
assert.equal(new URL(url).searchParams.get('id'),'p1');
assert.equal(getIncomingShare().kind,'post');
assert.equal(getIncomingShare('?gm-share=post&id='+ 'x'.repeat(190)),null,'reject giant ids');
console.log('PASS: report/block/hide and restore, history, opportunity filtering, share links, JSON persistence');
