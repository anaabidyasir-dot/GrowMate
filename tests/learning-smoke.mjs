import assert from 'node:assert/strict';
import {authorFor,authorMarkup,ratingMarkup,ratingFor,ownsMaterial,parseMaterialInput,materialFormMarkup,chapterFieldMarkup} from '../src/learning-ux.js';
const db={me:{email:'murid@example.com',name:'Dewi',program:'Informatika',avatar:''},moduleRatings:{}};
const sample={id:'m1',category:'Algoritma & Pemrograman',title:'Perulangan',summary:'Memahami alur',content:['If','While'],duration:35,progress:0,peers:[]};
assert.equal(authorFor(sample,db).name,'Kenzie Raditya Pratama');
assert.match(authorMarkup(sample,db,true),/Kenzie/);
assert.match(ratingMarkup(sample,db),/Belum dinilai/);
assert.equal(ratingFor(sample,db).score,0);
db.moduleRatings.m1=4;
assert.equal(ratingFor(sample,db).score,4);
assert.match(ratingMarkup(sample,db,true),/Beri 5 dari 5 bintang/);
assert.match(ratingMarkup(sample,db),/4,0/);
const own={id:'module-personal',authorId:'me',title:'Belajar <script>alert(1)<\/script>',category:'Desain Produk',summary:'Ringkasan',duration:30,content:['Dasar UI']};
assert.equal(ownsMaterial(own,db),true);
assert.equal(ownsMaterial(sample,db),false);
assert.match(materialFormMarkup(own),/Edit|Perbarui materi/);
assert.doesNotMatch(materialFormMarkup(own),/<script>/);
assert.match(materialFormMarkup(null),/chapter_0/);
assert.match(chapterFieldMarkup(6),/chapter_6/);
const values={title:'  Materi baru  ',summary:'Belajar topik A',category:'Desain Produk',duration:'45',chapter_1:' Bab kedua ',chapter_0:'Bab pertama'};
assert.deepEqual(parseMaterialInput(values),{title:'Materi baru',summary:'Belajar topik A',category:'Desain Produk',duration:45,content:['Bab pertama','Bab kedua']});
assert.equal(parseMaterialInput({...values,duration:'999'}),null);
assert.equal(parseMaterialInput({...values,title:''}),null);
console.log('PASS: penulis, rating lokal, editor judul per bab, validasi dan escape HTML');
